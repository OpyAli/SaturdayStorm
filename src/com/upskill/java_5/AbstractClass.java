package com.upskill.java_5;

public abstract class AbstractClass {

	public abstract void icar();
	public abstract void icolor();
	public abstract int iseat();
	
	public void car() {
		System.out.println("Tesla");
		
	}
	
	public void color() {
		System.out.println("Red");
		
	}
	
	public int seat() {
		return 7;
		
	}
}
